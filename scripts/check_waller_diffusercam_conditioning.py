#!/usr/bin/env python3
"""Reproducible conditioning audit for the pinned public DiffuserCam PSF stack.

The audit has two deliberately separated scopes:

1. ``depth_only_same_lateral``: inspect the calibrated depth PSFs directly.
2. A declared finite source grid whose recorded columns are generated by the
   *same discrete forward operator implemented in the pinned Waller solver*:

       PSF bias subtraction
       -> depth flip + source circshift
       -> global PSF-stack normalization
       -> lateral pad-both
       -> ifftshift
       -> circular 3-D convolution
       -> central 2-D sensor crop at output z=0.

For selected impulses, circular convolution is evaluated by rolling the exact
source convolution kernel. One selected column is independently checked against
an FFT convolution evaluation. The resulting finite same-H column family is
normalized to compute mutual coherence, from which a Gershgorin lower bound is
compiled for differences of sparse scenes. This is a certificate for exactly
the declared finite source family; it is not an all-resolution camera RIP claim.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import tempfile
import urllib.request
from pathlib import Path

import numpy as np
from scipy.io import loadmat

PINNED_COMMIT = "c8516cb8f482c2bb15e75ebebd91a74b88732c95"
PSF_URL = (
    "https://raw.githubusercontent.com/Waller-Lab/DiffuserCam/"
    + PINNED_COMMIT
    + "/example_data/example_psfs.mat"
)
PSF_GIT_BLOB_SHA1 = "db59065bdaf44fe771a6d3fbe22ae3c703527b5f"
PSF_EXPECTED_BYTES = 10823885


def download_psf(path: Path) -> None:
    urllib.request.urlretrieve(PSF_URL, path)


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def source_processed_psf(calibrated: np.ndarray) -> np.ndarray:
    """Mirror the pinned ADMM3D_solver.m flip/shift/global normalization."""
    if calibrated.ndim != 3:
        raise ValueError("calibrated PSF stack must be 3-D")
    nz = calibrated.shape[2]
    processed = np.flip(calibrated, axis=2)
    # MATLAB: circshift(flip(psf,3), ceil(Nz/2)+1, 3)
    processed = np.roll(processed, int(math.ceil(nz / 2.0)) + 1, axis=2)
    norm = float(np.linalg.norm(processed.ravel()))
    if norm == 0.0:
        raise RuntimeError("calibrated source PSF stack has zero norm")
    return processed / norm


def source_convolution_kernel(processed_psf: np.ndarray) -> tuple[np.ndarray, int, int]:
    """Mirror pad2d + ifftshift from the pinned source before FFT convolution."""
    ny, nx, _ = processed_psf.shape
    p1 = ny // 2
    p2 = nx // 2
    padded = np.pad(processed_psf, ((p1, p1), (p2, p2), (0, 0)), mode="constant")
    # MATLAB: Hs = fftn(ifftshift(pad2d(psf)))
    kernel = np.fft.ifftshift(padded)
    return kernel, p1, p2


def padded_circular_convolution_crop(
    kernel: np.ndarray,
    p1: int,
    p2: int,
    impulse_index: tuple[int, int, int],
) -> np.ndarray:
    """Exact impulse column for the pinned discrete H, using circular convolution."""
    iy, ix, iz = impulse_index
    py, px, pz = kernel.shape
    if not (0 <= iy < py and 0 <= ix < px and 0 <= iz < pz):
        raise ValueError("impulse index outside padded source volume")

    # Circular convolution with a unit impulse equals a circular kernel shift.
    response = np.roll(kernel, shift=(iy, ix, iz), axis=(0, 1, 2))

    y_slice = slice(p1, py - p1 if p1 else py)
    x_slice = slice(p2, px - p2 if p2 else px)
    # MATLAB crop3d = crop2d(x(:,:,1)); Python z index 0 is MATLAB plane 1.
    return np.asarray(response[y_slice, x_slice, 0], dtype=np.float64)


def fft_impulse_column_crosscheck(
    kernel: np.ndarray,
    p1: int,
    p2: int,
    impulse_index: tuple[int, int, int],
) -> float:
    """Cross-check roll identity against literal FFT multiplication for one column."""
    impulse = np.zeros_like(kernel)
    impulse[impulse_index] = 1.0
    via_fft = np.real(np.fft.ifftn(np.fft.fftn(kernel) * np.fft.fftn(impulse)))
    py, px, _ = kernel.shape
    y_slice = slice(p1, py - p1 if p1 else py)
    x_slice = slice(p2, px - p2 if p2 else px)
    via_fft_crop = via_fft[y_slice, x_slice, 0]
    via_roll = padded_circular_convolution_crop(kernel, p1, p2, impulse_index)
    return float(np.max(np.abs(via_fft_crop - via_roll)))


def source_forward_selected_columns(
    calibrated: np.ndarray,
    lateral_radius: int,
    lateral_step: int,
) -> tuple[np.ndarray, list[tuple[int, int, int]], float, tuple[int, int, int]]:
    """Build selected columns of the exact pinned source H on a finite source grid."""
    if lateral_radius < 0:
        raise ValueError("lateral_radius must be nonnegative")
    if lateral_step <= 0:
        raise ValueError("lateral_step must be positive")

    processed = source_processed_psf(calibrated)
    kernel, p1, p2 = source_convolution_kernel(processed)
    py, px, pz = kernel.shape
    cy, cx = py // 2, px // 2
    offsets = range(-lateral_radius, lateral_radius + 1, lateral_step)

    columns: list[np.ndarray] = []
    labels: list[tuple[int, int, int]] = []
    first_index: tuple[int, int, int] | None = None
    for iz in range(pz):
        for dy in offsets:
            for dx in offsets:
                iy, ix = cy + dy, cx + dx
                if not (0 <= iy < py and 0 <= ix < px):
                    continue
                idx = (iy, ix, iz)
                recorded = padded_circular_convolution_crop(kernel, p1, p2, idx)
                col = recorded.reshape(-1)
                if np.linalg.norm(col) == 0.0:
                    continue
                if first_index is None:
                    first_index = idx
                columns.append(col)
                labels.append((iz, dy, dx))

    if not columns or first_index is None:
        raise RuntimeError("declared selected source grid produced no nonzero H columns")

    fft_error = fft_impulse_column_crosscheck(kernel, p1, p2, first_index)
    return np.column_stack(columns), labels, fft_error, kernel.shape


def translated_column_mutual_coherence(columns: np.ndarray) -> tuple[float, float]:
    """Return normalized mutual coherence and minimum unnormalized column norm."""
    norms = np.linalg.norm(columns, axis=0)
    if np.any(norms == 0):
        raise RuntimeError("selected source-H column family contains a zero column")
    normalized = columns / norms[None, :]
    gram = normalized.T @ normalized
    np.fill_diagonal(gram, 0.0)
    mu = float(np.max(np.abs(gram))) if gram.size else 0.0
    return mu, float(np.min(norms))


def gershgorin_sparse_lower_bound(mutual_coherence: float, sparse_order: int) -> float:
    """Lower eigenvalue bound for every normalized Gram submatrix of this order."""
    if sparse_order < 1:
        raise ValueError("sparse_order must be >= 1")
    return max(0.0, 1.0 - (sparse_order - 1) * mutual_coherence)


def max_scene_sparsity_for_positive_bound(mutual_coherence: float, max_columns: int) -> int:
    """Largest k with a positive coherence bound for differences of two k-sparse scenes."""
    best = 0
    for k in range(1, max_columns + 1):
        difference_order = min(2 * k, max_columns)
        if gershgorin_sparse_lower_bound(mutual_coherence, difference_order) > 0.0:
            best = k
        else:
            break
    return best


def analyse(path: Path, lateral_radius: int = 1, lateral_step: int = 1) -> dict:
    if path.stat().st_size != PSF_EXPECTED_BYTES:
        raise RuntimeError(
            f"unexpected example_psfs.mat byte count: {path.stat().st_size}"
        )

    data = loadmat(path)
    if "psf" not in data:
        raise RuntimeError("pinned MAT artifact does not contain variable 'psf'")

    psf = np.asarray(data["psf"], dtype=np.float64)
    if psf.ndim != 3:
        raise RuntimeError(f"expected 3-D PSF stack, got shape {psf.shape}")

    # Match DiffuserCam_main.m at the pinned commit.
    psf_bias = 102.0
    calibrated = psf - psf_bias

    # Depth-only diagnostic uses the same global scaling as the source solver.
    processed = source_processed_psf(calibrated)
    source_stack_norm = float(np.linalg.norm(calibrated.ravel()))
    ny, nx, nz = processed.shape
    depth_matrix = processed.reshape(ny * nx, nz)
    norms = np.linalg.norm(depth_matrix, axis=0)
    if np.any(norms == 0):
        raise RuntimeError("at least one depth PSF has zero norm after source preprocessing")

    normalized = depth_matrix / norms[None, :]
    gram = normalized.T @ normalized
    offdiag = gram - np.eye(nz)
    max_abs_offdiag = float(np.max(np.abs(offdiag))) if nz > 1 else 0.0
    adjacent_abs = (
        np.abs(np.diag(gram, k=1)) if nz > 1 else np.asarray([], dtype=np.float64)
    )

    singular_values = np.linalg.svd(depth_matrix, compute_uv=False)
    tol = np.finfo(np.float64).eps * max(depth_matrix.shape) * singular_values[0]
    numerical_rank = int(np.count_nonzero(singular_values > tol))
    condition = (
        float(singular_values[0] / singular_values[-1])
        if singular_values[-1] > 0
        else float("inf")
    )

    selected_h, labels, fft_crosscheck_error, padded_shape = source_forward_selected_columns(
        calibrated,
        lateral_radius=lateral_radius,
        lateral_step=lateral_step,
    )
    mu, min_column_norm = translated_column_mutual_coherence(selected_h)
    max_scene_k = max_scene_sparsity_for_positive_bound(mu, selected_h.shape[1])

    sparse_examples = {}
    for scene_k in (1, 2, 4, 8):
        difference_order = min(2 * scene_k, selected_h.shape[1])
        lower_normalized = gershgorin_sparse_lower_bound(mu, difference_order)
        lower_gain = min_column_norm * math.sqrt(lower_normalized)
        kappa_upper = (1.0 / lower_gain) if lower_gain > 0.0 else None
        sparse_examples[str(scene_k)] = {
            "difference_sparse_order": int(difference_order),
            "normalized_gram_lower_bound": float(lower_normalized),
            "sensor_gain_lower_bound": float(lower_gain),
            "restricted_kappa_upper_bound": kappa_upper,
        }

    global_sparse_inverse_certificate = max_scene_k >= 1

    return {
        "source_repository": "Waller-Lab/DiffuserCam",
        "source_commit": PINNED_COMMIT,
        "artifact": "example_data/example_psfs.mat",
        "artifact_git_blob_sha1": PSF_GIT_BLOB_SHA1,
        "artifact_sha256": sha256_file(path),
        "artifact_bytes": int(path.stat().st_size),
        "psf_shape": [int(ny), int(nx), int(nz)],
        "source_preprocessing": {
            "psf_bias": psf_bias,
            "global_psf_stack_norm": source_stack_norm,
            "depth_flip": True,
            "depth_circshift": int(math.ceil(nz / 2.0)) + 1,
            "lateral_pad_both": [int(ny // 2), int(nx // 2)],
            "ifftshift_before_fftn": True,
            "recorded_output": "central_sensor_crop_at_z0",
        },
        "diagnostic_scope": "depth_only_same_lateral",
        "depth_columns": int(nz),
        "numerical_rank": numerical_rank,
        "max_abs_normalized_depth_gram_offdiag": max_abs_offdiag,
        "max_abs_adjacent_depth_gram": (
            float(np.max(adjacent_abs)) if adjacent_abs.size else 0.0
        ),
        "mean_abs_adjacent_depth_gram": (
            float(np.mean(adjacent_abs)) if adjacent_abs.size else 0.0
        ),
        "largest_singular_value": float(singular_values[0]),
        "smallest_singular_value": float(singular_values[-1]),
        "depth_matrix_condition_number": condition,
        "selected_source_h_family": {
            "lateral_radius_pixels": int(lateral_radius),
            "lateral_step_pixels": int(lateral_step),
            "column_count": int(selected_h.shape[1]),
            "label_count": len(labels),
            "padded_source_shape": [int(v) for v in padded_shape],
            "operator": "padded_circular_convolution_crop",
            "fft_vs_roll_max_abs_error_first_column": fft_crosscheck_error,
        },
        "translated_column_mutual_coherence": mu,
        "minimum_translated_column_norm": min_column_norm,
        "max_scene_sparsity_for_positive_bound": int(max_scene_k),
        "gershgorin_sparse_lower_bound": sparse_examples,
        "global_sparse_inverse_certificate": global_sparse_inverse_certificate,
        "certificate_scope": "declared_finite_selected_columns_of_pinned_source_H",
        "all_resolution_camera_rip_certificate": False,
        "matched_photon_comparison": False,
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--psf", type=Path, default=None)
    parser.add_argument("--json-out", type=Path, default=None)
    parser.add_argument("--lateral-radius", type=int, default=1)
    parser.add_argument("--lateral-step", type=int, default=1)
    args = parser.parse_args()

    kwargs = {
        "lateral_radius": args.lateral_radius,
        "lateral_step": args.lateral_step,
    }
    if args.psf is None:
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "example_psfs.mat"
            download_psf(path)
            result = analyse(path, **kwargs)
    else:
        result = analyse(args.psf, **kwargs)

    encoded = json.dumps(result, indent=2, sort_keys=True, allow_nan=False)
    print(encoded)
    if args.json_out is not None:
        args.json_out.write_text(encoded + "\n")


if __name__ == "__main__":
    main()
