#!/usr/bin/env python3
"""Finite BIDI consumer adequacy vs stronger physical KK steelman.
No physical source, empirical bound, 5D derivation, or Agda proof is inferred.
"""
from itertools import product
import sympy as sp

states = list(product((False, True), repeat=5))
# state = gauge, radion, source, nodal, azimuthal_metric

def gauge(s): return s[0]
def radion(s): return s[1]
def source(s): return s[2]
def orbit(s): return s[3]
def metric(s): return (s[3],s[4])
def steelman(s): return (s[1],s[2])
def both(s): return (orbit(s),steelman(s))

def factorization(observer, consumer):
    seen = {}
    for state in states:
        key = observer(state)
        value = consumer(state)
        if key in seen and seen[key][1] != value:
            return False, (seen[key][0], state)
        seen.setdefault(key, (state,value))
    return True, None

checks = [
    ('gauge -> gauge', gauge, gauge, True),
    ('gauge -> radion', gauge, radion, False),
    ('nodal -> nodal', orbit, orbit, True),
    ('nodal -> steelman', orbit, steelman, False),
    ('nodal+steelman -> steelman', both, steelman, True),
    ('nodal+steelman -> nodal', both, orbit, True),
    ('g_tphi indicator alone -> full metric pair', orbit, metric, False),
    ('full metric pair -> full metric pair', metric, metric, True),
]
for name, obs, query, expected in checks:
    valid, witness = factorization(obs,query)
    assert valid == expected, (name, valid)
    if not valid:
        x,y=witness
        assert obs(x)==obs(y) and query(x)!=query(y)
    print(f"{'FACTORS' if valid else 'NON-DESCENT'}: {name}" +
          (f' witness={witness}' if witness else ''))

required = (
    'single_action', 'compactification', 'derived_matter_coupling',
    'conserved_earth_source', 'regular_matching', 'radion_stability',
    'known_gravity_tests', 'physical_orbit'
)
# The populated evidence is deliberately ONLY local circle geometry,
# never a receipt for a physical Earth compactification.
assets = {
    'GR_times_circle_product': {'compactification'},
    'boosted_Kerr_black_string': {'compactification'},
    'null_KK_pp_wave': {'compactification'},
    'linear_massive_radion_source': set(),
    'torque_SO3_orientation': set(),
    'KK_U1_gauge_shift': set(),
    'Higgs_electroweak_boundary': set(),
}
for name, discharged in assets.items():
    assert discharged <= set(required)
    missing=set(required)-discharged
    assert missing
    print(f'{name}: steelman NOT discharged; {len(missing)} obligations remain')
assert not any(set(required)<=x for x in assets.values())

# Character obstruction: so(3) generators are generated by commutators,
# whereas u(1) Lie bracket vanishes.
cx,cy,cz=sp.symbols('cx cy cz')
constraints=sp.Matrix([cx,cy,cz])
assert sp.solve(list(constraints),(cx,cy,cz)) == {cx:0,cy:0,cz:0}
assert constraints.jacobian([cx,cy,cz]).rank()==3

print('PASS finite BIDI counterexamples and Lie algebra character test')
print('WARNING: no physical Earth KK action or empirical validation was proved')
