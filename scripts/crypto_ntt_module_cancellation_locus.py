#!/usr/bin/env python3
"""Exact blue-team cancellation-locus probe for the ML-KEM NTT module map.

The full-module uncertainty lift has a clean hypothesis: every local k x k
matrix over K_i = F_q[u]/(u^2-gamma_i) is invertible.  This file shows why that
hypothesis is exact rather than cosmetic.

If one local matrix A_i is singular, CRT/NTT coordinates expose a nonzero
module vector supported only at residue i and lying in ker(A_i).  Its public
image is zero.  Conversely, if every A_i is invertible, the global module map
has no nonzero kernel and preserves zero/nonzero residue support exactly.

The finite-field Fourier uncertainty principle then controls how localized a
kernel/cancellation vector can be back in coefficient coordinates.  A vector
supported on m Fourier residues must have coefficient support at least 128/m,
and the subgroup/annihilator equality family attains product 128 exactly.

Primary source:
  NIST FIPS 203, "Module-Lattice-Based Key-Encapsulation Mechanism Standard",
  2024. DOI: 10.6028/NIST.FIPS.203.

Uncertainty reference:
  Martino Borello, Patrick Sole, "The uncertainty principle over finite
  fields", Discrete Mathematics 345 (2022).
  DOI: 10.1016/j.disc.2021.112670.

This is structural analysis, not an operational attack.
"""

import numpy as np

Q = 3329
ZETA = 17
HALF = 128


def bitrev7(i: int) -> int:
    return int(f"{i:07b}"[::-1], 2)


PERM = np.array([bitrev7(i) for i in range(HALF)], dtype=np.int64)
INVPERM = np.empty(HALF, dtype=np.int64)
for i, p in enumerate(PERM):
    INVPERM[p] = i

OMEGA = pow(ZETA, 2, Q)
FOURIER = np.array(
    [[pow(OMEGA, r * j, Q) for j in range(HALF)] for r in range(HALF)],
    dtype=np.int64,
)
INV_HALF = pow(HALF, Q - 2, Q)
FOURIER_INV = np.array(
    [[pow(OMEGA, (-r * j) % HALF, Q) for r in range(HALF)] for j in range(HALF)],
    dtype=np.int64,
)
FOURIER_INV = (INV_HALF * FOURIER_INV) % Q
DIAGONAL = np.array([pow(ZETA, j, Q) for j in range(HALF)], dtype=np.int64)
DIAGONAL_INV = np.array([pow(int(x), Q - 2, Q) for x in DIAGONAL], dtype=np.int64)


def fips_forward(x: np.ndarray) -> np.ndarray:
    natural = (FOURIER @ ((DIAGONAL * x) % Q)) % Q
    return natural[PERM]


def fips_inverse(y: np.ndarray) -> np.ndarray:
    natural = np.asarray(y, dtype=np.int64)[INVPERM]
    return (DIAGONAL_INV * ((FOURIER_INV @ natural) % Q)) % Q


def support(x: np.ndarray) -> int:
    return int(np.count_nonzero(np.asarray(x) % Q))


def verify_single_residue_atoms() -> None:
    for residue in (0, 1, 2, 17, 64, 127):
        y = np.zeros(HALF, dtype=np.int64)
        y[residue] = 1
        x = fips_inverse(y)
        assert np.array_equal(fips_forward(x), y)
        assert support(x) == HALF
        assert support(y) == 1
        assert support(x) * support(y) == HALF


def verify_subgroup_extremizers() -> None:
    # Subgroup structure is in natural Fourier order.  FIPS row order is just
    # bit reversal, so build H in natural order and then permute it.
    for m in (1, 2, 4, 8, 16, 32, 64, 128):
        stride = HALF // m
        y_natural = np.zeros(HALF, dtype=np.int64)
        for t in range(m):
            y_natural[t * stride] = 1
        y_fips = y_natural[PERM]
        x = fips_inverse(y_fips)
        assert np.array_equal(fips_forward(x), y_fips)
        assert support(y_fips) == m
        assert support(x) == HALF // m
        assert support(x) * support(y_fips) == HALF
        print(
            f"m={m:3d} source_support={support(x):3d} "
            f"residue_support={support(y_fips):3d} product={support(x)*support(y_fips)}"
        )


def verify_explicit_singular_kernel() -> None:
    # Over any K_i, diag(0,1) has kernel generated by (1,0).  Thus if one local
    # public matrix has this singular form, a residue-local hidden perturbation
    # in that kernel disappears completely under public multiplication.
    zero = (0, 0)
    one = (1, 0)
    matrix = ((zero, zero), (zero, one))
    vector = (one, zero)

    def kmul(a, b, gamma):
        return (
            (a[0] * b[0] + gamma * a[1] * b[1]) % Q,
            (a[0] * b[1] + a[1] * b[0]) % Q,
        )

    def kadd(a, b):
        return ((a[0] + b[0]) % Q, (a[1] + b[1]) % Q)

    gamma0 = pow(ZETA, 2 * bitrev7(0) + 1, Q)
    output = []
    for row in matrix:
        acc = zero
        for a, b in zip(row, vector):
            acc = kadd(acc, kmul(a, b, gamma0))
        output.append(acc)
    assert output == [zero, zero]

    # Choosing this kernel atom at one NTT residue forces a coefficient-dense
    # preimage: 128 source positions for the chosen parity component.
    spectral = np.zeros(HALF, dtype=np.int64)
    spectral[0] = 1
    source = fips_inverse(spectral)
    assert support(source) == 128
    assert support(spectral) == 1
    assert support(source) * support(spectral) == 128


def main() -> None:
    verify_single_residue_atoms()
    print("PASS: single-residue atoms are coefficient-dense and saturate 128")
    verify_subgroup_extremizers()
    print("PASS: all subgroup/annihilator cancellation extremizers saturate 128")
    verify_explicit_singular_kernel()
    print("PASS: a singular local module block creates an exact global cancellation direction")


if __name__ == "__main__":
    main()
