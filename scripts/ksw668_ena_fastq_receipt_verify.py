#!/usr/bin/env python3
"""P0 validate ALL original pigeon macrophage FASTQ bytes, not just receipt presence.

Source Lisowski et al. Science 2026 DOI 10.1126/science.ady2486;
public ENA PRJEB98986 original read_run file report and MD5.
Consumes an --execute --download-reads receipt generated by
scripts/ksw668_ena_reads_acquire.py and independently re-hashes every
local FASTQ, confirms ENA original MD5, local SHA256 and original byte count.
Never treats a JSON file's presence as raw-data provenance, nor pretends that
raw FASTQs are annotated single-cell/cell-type count matrices.
"""
import argparse,hashlib,json
from pathlib import Path

STUDY="PRJEB98986"
def sha_pair(path):
    md=hashlib.md5();sh=hashlib.sha256();size=0
    with Path(path).open("rb") as h:
        for block in iter(lambda:h.read(1<<20),b""):
            size+=len(block);md.update(block);sh.update(block)
    return size,md.hexdigest(),sh.hexdigest()

def verify(receipt):
    r=json.loads(Path(receipt).read_text(encoding="utf-8"))
    if r.get("study_accession")!=STUDY:
        raise ValueError("Wrong original ENA study accession")
    if r.get("fastq_downloaded") is not True:
        raise ValueError("Raw FASTQ not acquired; metadata-only receipt rejected")
    expected=r.get("files_expected")
    verified=r.get("files_verified")
    if not isinstance(expected,list) or not isinstance(verified,list) or not expected:
        raise ValueError("No source original ENA FASTQ files in receipt")
    if len(expected)!=len(verified):
        raise ValueError("Missing raw ENA files")
    known={entry["url"]:entry for entry in expected}
    results=[]
    for item in verified:
        if item["url"] not in known:
            raise ValueError("Unexpected original ENA accession/URL")
        src=known[item["url"]]
        if any(item.get(key)!=src.get(key) for key in
               ("run","experiment","sample","expected_md5","expected_bytes")):
            raise ValueError("ENA source metadata changed between metadata and downloaded bytes")
        local=item.get("local_path")
        if not isinstance(local,str) or not local:
            raise ValueError("Missing original local FASTQ path")
        file=Path(local)
        if not file.is_file():raise ValueError("Missing actual FASTQ bytes: "+local)
        bytes_,md,sha=sha_pair(file)
        if (bytes_!=src["expected_bytes"] or
            bytes_!=item.get("verified_size") or
            md.lower()!=src["expected_md5"].lower() or
            sha.lower()!=item.get("sha256","").lower() or
            item.get("ena_md5_verified") is not True):
            raise ValueError("Wrong original ENA FASTQ size/MD5/SHA: "+local)
        results.append({"run":item["run"],"file":local,
                        "bytes":bytes_,"ENA_MD5":md,"local_SHA256":sha})
    if len({item["url"] for item in verified})!=len(verified):
        raise ValueError("Duplicate original FASTQ listed")
    return {"status":"PASS all original ENA FASTQ data rehashed, not just metadata",
            "source_original_DOI":"10.1126/science.ady2486",
            "ENA_study":STUDY,"raw_files":len(results),
            "raw_total_bytes":sum(item["bytes"] for item in results),
            "raw_verified":results,
            "gene_count_matrix_constructed":False,
            "pigeon_treatment_GPS_joins_done":False}

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--receipt",type=Path,required=True)
    p.add_argument("--out",type=Path)
    a=p.parse_args()
    r=verify(a.receipt)
    report=json.dumps(r,sort_keys=True,indent=2)+"\n"
    if a.out:a.out.write_text(report)
    print(report)

if __name__=="__main__":
    main()
