"""Finite Heaps discovery-count stochastic ordering under count majorization.

Use the canonical Zipf/Heaps count validator, expectations and majorization order.
Two distinct samplers are treated separately: IID with replacement, and a
uniform permutation of the original finite multiset without replacement.

Mathematics: elementary occupancy generating functions and classical
Hardy-Littlewood-Polya majorization (1934); temporality context Zimmerlin,
Louail, Moussallam and Barthelemy, Physical Review E 113 (2026), 054304.
Repository implementation: Johl Brown with OpenAI ChatGPT assistance,
2026-10-28. Exact Python checks are not Agda kernel proofs or empirical fits.
"""
from __future__ import annotations

from collections import defaultdict
from fractions import Fraction
from math import comb, factorial
from typing import Literal, Sequence

from zipf_heaps_bridge import (
    _validated_counts,
    expected_iid_vocabulary,
    expected_permutation_vocabulary,
    multiset_count_majorizes,
)

Sampler = Literal['iid', 'permutation']


def distinct_count_pmf(
    counts: Sequence[int], draws: int, sampler: Sampler
) -> tuple[Fraction, ...]:
    """Exact P(V_draws=j), j=0..K, from a finite generating function.

    IID: [z^t y^j] prod_i (1+y*(exp(p_i*z)-1)) * t!.
    Permutation: [z^t y^j] prod_i (1+y*((1+z)^f_i-1)) / C(N,t).
    The exponential generating function is truncated at t. No floating point.
    """
    c = _validated_counts(counts)
    n = sum(c)
    if (type(draws) is not int or draws < 0 or
            (sampler == 'permutation' and draws > n) or
            sampler not in ('iid', 'permutation')):
        raise ValueError('valid sampler and 0<=draws<=N for permutation; iid t>=0')
    # Dynamic polynomial coefficient indexed by (number of types, tokens).
    state: dict[tuple[int, int], Fraction] = {(0, 0): Fraction(1)}
    for freq in c:
        weights = [Fraction(1)]
        if sampler == 'iid':
            p = Fraction(freq, n)
            weights.extend(p ** r / factorial(r) for r in range(1, draws + 1))
        else:
            weights.extend(Fraction(comb(freq, r)) for r in range(1, min(freq, draws) + 1))
        nxt: dict[tuple[int, int], Fraction] = defaultdict(Fraction)
        for (types, used), value in state.items():
            for r, weight in enumerate(weights[:draws - used + 1]):
                nxt[(types + (r > 0), used + r)] += value * weight
        state = dict(nxt)
    scale = Fraction(factorial(draws)) if sampler == 'iid' else Fraction(1, comb(n, draws))
    pmf = tuple(state.get((j, draws), Fraction()) * scale for j in range(len(c) + 1))
    assert sum(pmf) == 1 and all(x >= 0 for x in pmf)
    expectation = sum((j * p for j, p in enumerate(pmf)), Fraction())
    expected = (expected_iid_vocabulary(tuple(Fraction(x, n) for x in c), draws)
                if sampler == 'iid' else expected_permutation_vocabulary(c, draws))
    assert expectation == expected
    return pmf


def upper_tails(pmf: Sequence[Fraction]) -> tuple[Fraction, ...]:
    """P(V >= j) for each j=0..K, including the sure event j=0."""
    running = Fraction()
    tails = []
    for mass in reversed(pmf):
        if not isinstance(mass, Fraction) or mass < 0:
            raise ValueError('nonnegative exact probabilities required')
        running += mass
        tails.append(running)
    if running != 1:
        raise ValueError('normalized probability distribution required')
    return tuple(reversed(tails))


def discovery_stochastic_majorization_certificate(
    concentrated: Sequence[int], dispersed: Sequence[int], draws: int
) -> dict[str, tuple[tuple[Fraction, ...], tuple[Fraction, ...]]]:
    """Executable finite first-order stochastic dominance for TWO samplers.

    When concentrated majorizes dispersed (same K,N, positive counts),
    P_concentrated(V_t>=j) <= P_dispersed(V_t>=j) for every j, in each sampler.
    The proof reduces to a one-token anti-Robin-Hood transfer between pair
    counts a>=b>=2 with constant a+b, conditional on pair-group positions.
    IID pair-both probability: 1-(a/(a+b))^m-(b/(a+b))^m.
    Permutation pair-both: 1-[C(a,m)+C(b,m)]/C(a+b,m).
    Both decrease under concentration by convexity. Classical integer
    majorization is generated by these transfers and relabeling.
    """
    if not multiset_count_majorizes(concentrated, dispersed):
        raise ValueError('requires equal K,N and majorization')
    if type(draws) is not int or not 0 <= draws <= sum(concentrated):
        raise ValueError('both samplers use a common prefix in [0,N]')
    out = {}
    for sampler in ('iid', 'permutation'):
        high = upper_tails(distinct_count_pmf(concentrated, draws, sampler))
        low = upper_tails(distinct_count_pmf(dispersed, draws, sampler))
        assert all(a <= b for a, b in zip(high, low))
        out[sampler] = (high, low)
    return out


def pair_second_type_cdf(a: int, b: int, pair_draws: int, sampler: Sampler) -> Fraction:
    """P(first two-type completion time <= m), conditional on m pair draws.

    At m=0 or 1 it is zero. Under a permutation the pair contains exactly
    a+b tokens; the convention C(x,m)=0 for x<m is explicit.
    """
    if (type(a) is not int or type(b) is not int or a < 1 or b < 1
            or type(pair_draws) is not int or pair_draws < 0
            or sampler not in ('iid', 'permutation')
            or (sampler == 'permutation' and pair_draws > a+b)):
        raise ValueError('positive pair, valid sampler and pair-draw horizon')
    if pair_draws < 2:
        return Fraction()
    total = a+b
    if sampler == 'iid':
        return 1 - Fraction(a,total)**pair_draws - Fraction(b,total)**pair_draws
    return 1 - Fraction(comb(a,pair_draws)+comb(b,pair_draws),comb(total,pair_draws))


def pair_pathwise_quantile_certificate(
    a: int, b: int, horizon: int, sampler: Sampler
) -> tuple[tuple[Fraction,int,int], ...]:
    """Finite exact coupling witness: concentrating a pair delays discovery.

    For a>=b>=2, use one common uniform quantile U for the first group draw
    on which BOTH subtypes have appeared, before and after a->a+1,b->b-1.
    For every rational interval between CDF breakpoints, return the common
    U midpoint and the two coupled completion times; horizon+1 means unseen.
    Each witness orders all m<=horizon SIMULTANEOUSLY, not just a marginal.
    With the same merged-pair and outside-type schedule this proves an
    all-prefix coupling for the one-transfer Heaps diversity trajectory.
    """
    if (type(a) is not int or type(b) is not int or a < b or b < 2
            or type(horizon) is not int or horizon < 0
            or sampler not in ('iid','permutation')
            or (sampler == 'permutation' and horizon > a+b)):
        raise ValueError('a>=b>=2, valid sampler and horizon')
    concentrated = tuple(pair_second_type_cdf(a+1,b-1,m,sampler)
                         for m in range(horizon+1))
    dispersed = tuple(pair_second_type_cdf(a,b,m,sampler)
                      for m in range(horizon+1))
    assert all(x<=y for x,y in zip(concentrated,dispersed))
    cuts = sorted(set((Fraction(), Fraction(1), *concentrated, *dispersed)))
    witnesses = []
    for lo,hi in zip(cuts,cuts[1:]):
        u = (lo+hi)/2
        tc = next((m for m,c in enumerate(concentrated) if c>=u), horizon+1)
        td = next((m for m,c in enumerate(dispersed) if c>=u), horizon+1)
        assert tc>=td
        assert all(int(tc<=m)<=int(td<=m) for m in range(horizon+1))
        witnesses.append((u,tc,td))
    return tuple(witnesses)
