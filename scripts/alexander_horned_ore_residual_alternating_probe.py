#!/usr/bin/env python3
"""Hatcher commutator tower -> finite A5 actor, exact finite regression.

Primary mathematical dependency for arbitrary finite alternating targets:
Ore (1951); Liebeck/O'Brien/Shalev/Tiep (2010), Ore conjecture.

This executable verifies the *local commutator-lifting step* and its
word-evaluation naturality, not the entire infinite residual-finiteness
theorem or the geometric horned-sphere identification.
"""
from itertools import permutations, product

IDENTITY = tuple(range(5))

def mul(a, b):
    return tuple(a[b[i]] for i in range(5))

def inv(a):
    return tuple(a.index(i) for i in range(5))

def comm(a, b):
    return mul(mul(mul(a, b), inv(a)), inv(b))

def even(a):
    return sum(a[i] > a[j] for i in range(5)
               for j in range(i + 1, 5)) % 2 == 0

A5 = tuple(p for p in permutations(range(5)) if even(p))
assert len(A5) == 60
WITNESS = {}
for a in A5:
    for b in A5:
        WITNESS.setdefault(comm(a, b), (a, b))
assert len(WITNESS) == 60

def word_inverse(w):
    return tuple((a, -s) for a, s in reversed(w))

def reduce_word(w):
    stack = []
    for x in w:
        if stack and x == (stack[-1][0], -stack[-1][1]):
            stack.pop()
        else:
            stack.append(x)
    return tuple(stack)

def word_expand(w):
    result = []
    for (sector, path), sign in w:
        a = ((sector, path + (0,)), 1)
        b = ((sector, path + (1,)), 1)
        block = (a, b, (a[0], -1), (b[0], -1))
        result.extend(block if sign == 1 else word_inverse(block))
    return reduce_word(result)

def evaluate(w, assignment):
    value = IDENTITY
    for name, sign in w:
        a = assignment[name]
        value = mul(value, a if sign > 0 else inv(a))
    return value

def next_assignment(old):
    out = {}
    for (sector, path), q in old.items():
        a, b = WITNESS[q]
        out[(sector, path + (0,))] = a
        out[(sector, path + (1,))] = b
        assert comm(a, b) == q
    return out

def check():
    # The stage-1 free group has 6 generators. Pick their A5 images
    # independently, including a pair deliberately distinguished.
    stage = {
        (c, (i,)): A5[(13 * c + 9 * i + 1) % 60]
        for c, i in product(range(3), range(2))
    }
    # All 6 length-one words and short inverse/commutator products.
    gens = [((name, 1),) for name in stage]
    words = gens + [word_inverse(g) for g in gens]
    words += [reduce_word(a + b) for a in gens for b in gens]
    words += [reduce_word(a + b + word_inverse(a) + word_inverse(b))
              for a in gens for b in gens]
    # Each step is an actual homomorphism on all reduced words;
    # no finite commutator pair was assumed to be generated by a scalar.
    for level in range(1, 5):
        successor = next_assignment(stage)
        for w in words:
            assert evaluate(word_expand(w), successor) == evaluate(w, stage)
        words = [word_expand(w) for w in words]
        stage = successor

    # The regular action of A5 has a literal faithful matrix
    # realization on 60 basis vectors over Z, hence every Qp.
    for q in A5:
        orbit = {mul(q, x) for x in A5}
        assert len(orbit) == 60
        assert (mul(q, IDENTITY) == IDENTITY) == (q == IDENTITY)

    # Binary -> two-point balanced-ternary subcarrier; full ternary
    # -> 2-bit code with reserved 11: labels, NOT 2- vs 3-adic group maps.
    binary_to_trit = {0: -1, 1: +1}
    trit_to_bits = {-1: (0, 0), 0: (0, 1), 1: (1, 0)}
    bits_to_trit = {v: k for k, v in trit_to_bits.items()}
    for b in (0, 1):
        assert bits_to_trit[trit_to_bits[binary_to_trit[b]]] == binary_to_trit[b]
    for t in (-1, 0, 1):
        assert bits_to_trit[trit_to_bits[t]] == t
    assert (1, 1) not in bits_to_trit

    print("A5 commutator section: 60/60 elements")
    print("Ore lift / evaluated free words: levels 1..5 PASS")
    print("A5 faithful 60-coordinate regular action (integral): PASS")
    print("Existing binary-in-ternary and ternary-to-two-bit codec roundtrips: PASS")
    print("All-stage group separation / geometric pi1 / Agda kernel: NOT tested")

if __name__ == "__main__":
    check()
