#!/usr/bin/env python3
"""Finite probe for the currently formalised appraisal-A hyperfabric action.

The two generators mirror the Agda definitions on one ternary appraisal voxel:
  S(x,y,z) = (y,x,z)
  F(x,y,z) = (-x,y,z)
over F3.  They act trivially on the interaction and appraisal-B factors, so
conjugacy/cycle data on the full 27^3 hyperfabric is induced from this 27-point
factor.  This script deliberately studies only the subgroup generated by S,F;
it does not claim this subgroup is the full hyperfabric symmetry group or a
Monster subgroup.
"""

from collections import deque, Counter
from itertools import product

POINTS = tuple(product(range(3), repeat=3))
INDEX = {p: i for i, p in enumerate(POINTS)}


def neg(x: int) -> int:
    return (-x) % 3


def swap_xy(p):
    x, y, z = p
    return (y, x, z)


def flip_x(p):
    x, y, z = p
    return (neg(x), y, z)


def permutation(f):
    return tuple(INDEX[f(p)] for p in POINTS)


def compose(a, b):
    """a after b."""
    return tuple(a[b[i]] for i in range(len(a)))


def inverse(a):
    out = [0] * len(a)
    for i, j in enumerate(a):
        out[j] = i
    return tuple(out)


def generated_group(generators):
    identity = tuple(range(len(POINTS)))
    seen = {identity}
    q = deque([identity])
    while q:
        g = q.popleft()
        for s in generators:
            h = compose(s, g)
            if h not in seen:
                seen.add(h)
                q.append(h)
    return tuple(seen)


def order(g):
    identity = tuple(range(len(g)))
    h = identity
    for n in range(1, 1000):
        h = compose(g, h)
        if h == identity:
            return n
    raise RuntimeError("order bound exceeded")


def cycle_type(g):
    seen = set()
    sizes = []
    for i in range(len(g)):
        if i in seen:
            continue
        j = i
        n = 0
        while j not in seen:
            seen.add(j)
            n += 1
            j = g[j]
        sizes.append(n)
    return tuple(sorted(Counter(sizes).items()))


def conjugacy_classes(group):
    remaining = set(group)
    classes = []
    while remaining:
        g = next(iter(remaining))
        cls = {compose(compose(h, g), inverse(h)) for h in group}
        classes.append(tuple(cls))
        remaining -= cls
    return classes


def full_fabric_fixed_points(local_fixed):
    # S,F act on appraisal-A only.  Interaction and appraisal-B each have 27 states.
    return local_fixed * 27 * 27


def main():
    S = permutation(swap_xy)
    F = permutation(flip_x)
    group = generated_group((S, F))
    classes = conjugacy_classes(group)

    print(f"local_carrier=27")
    print(f"full_hyperfabric=19683")
    print(f"generated_group_order={len(group)}")
    print(f"conjugacy_class_count={len(classes)}")

    rows = []
    for cls in classes:
        g = cls[0]
        fixed = sum(1 for i, j in enumerate(g) if i == j)
        rows.append((order(g), len(cls), fixed, full_fabric_fixed_points(fixed), cycle_type(g)))

    for i, row in enumerate(sorted(rows), start=1):
        elem_order, cls_size, fixed27, fixed19683, cycles = row
        print(
            f"class_{i}: order={elem_order} size={cls_size} "
            f"fixed27={fixed27} fixed19683={fixed19683} cycles27={cycles}"
        )

    # Fail closed on the currently intended small-generator facts.
    assert compose(S, F) != compose(F, S)
    assert len(group) == 8
    assert len(classes) == 5


if __name__ == "__main__":
    main()
