#!/usr/bin/env python3
"""Render a finite DASHI theory, inspect the raster with OpenCV, emit a receipt + Lean model.

The OpenCV result is deliberately treated as empirical evidence, not proof authority.
The exact semantic boundary lives in DASHI/Core/IntrospectiveVisualRoundTripExact.agda.
"""

import argparse
import json
from pathlib import Path

import cv2
import numpy as np

NODES = {
    "source": (80, 80),
    "projection": (240, 80),
    "fibre": (80, 240),
    "refinement": (240, 240),
}

EDGES = [
    ("source", "projection"),
    ("source", "fibre"),
    ("projection", "refinement"),
    ("fibre", "refinement"),
]


def render(path: Path) -> None:
    image = np.full((320, 320), 255, dtype=np.uint8)
    for source, target in EDGES:
        cv2.line(image, NODES[source], NODES[target], 0, 3, cv2.LINE_8)
    for point in NODES.values():
        cv2.circle(image, point, 12, 0, -1, cv2.LINE_8)
    if not cv2.imwrite(str(path), image):
        raise RuntimeError(f"failed to write {path}")


def detect(path: Path) -> dict:
    image = cv2.imread(str(path), cv2.IMREAD_GRAYSCALE)
    if image is None:
        raise RuntimeError(f"failed to read {path}")

    inverted = cv2.threshold(image, 127, 255, cv2.THRESH_BINARY_INV)[1]
    windows = {
        "source": (40, 40, 120, 120),
        "projection": (200, 40, 280, 120),
        "fibre": (40, 200, 120, 280),
        "refinement": (200, 200, 280, 280),
    }

    detected_nodes = {}
    for name, (x0, y0, x1, y1) in windows.items():
        roi = inverted[y0:y1, x0:x1]
        contours, _ = cv2.findContours(roi, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
        points = []
        for contour in contours:
            moments = cv2.moments(contour)
            if moments["m00"]:
                points.append(
                    (
                        x0 + moments["m10"] / moments["m00"],
                        y0 + moments["m01"] / moments["m00"],
                    )
                )
        if not points:
            raise RuntimeError(f"node not detected: {name}")
        target = np.array(NODES[name], dtype=float)
        point = min(points, key=lambda p: np.linalg.norm(np.array(p) - target))
        detected_nodes[name] = [round(point[0], 3), round(point[1], 3)]

    detected_edges = []
    for source, target in EDGES:
        p1 = np.array(NODES[source])
        p2 = np.array(NODES[target])
        mask = np.zeros_like(inverted)
        cv2.line(mask, tuple(p1), tuple(p2), 255, 9)
        for point in NODES.values():
            cv2.circle(mask, point, 18, 0, -1)
        pixels = inverted[mask == 255]
        occupancy = float((pixels > 0).mean()) if pixels.size else 0.0
        detected_edges.append(
            {
                "from": source,
                "to": target,
                "occupancy": round(occupancy, 4),
                "detected": occupancy > 0.45,
            }
        )

    return {
        "schema": "dashi.introspective-vision-receipt.v1",
        "image": {"width": int(image.shape[1]), "height": int(image.shape[0])},
        "nodes": detected_nodes,
        "edges": detected_edges,
        "all_expected_edges_detected": all(edge["detected"] for edge in detected_edges),
        "claim_boundary": (
            "OpenCV observations are empirical receipts; they do not certify semantic "
            "faithfulness without the separately proved rendering/extraction contract."
        ),
    }


def emit_lean(receipt: dict, path: Path) -> None:
    if not receipt["all_expected_edges_detected"]:
        raise RuntimeError("refusing Lean emission: expected visual structure not recovered")

    path.write_text(
        """/- Auto-generated by scripts/introspective_visual_roundtrip.py.
   This models the OpenCV receipt; it does not prove OpenCV correctness. -/

inductive VisionNode where
  | source | projection | fibre | refinement
  deriving DecidableEq, Repr

structure VisionEdge where
  src : VisionNode
  dst : VisionNode
  deriving DecidableEq, Repr

def detectedEdges : List VisionEdge :=
  [ { src := .source, dst := .projection }
  , { src := .source, dst := .fibre }
  , { src := .projection, dst := .refinement }
  , { src := .fibre, dst := .refinement } ]

theorem detectedEdgeCount : detectedEdges.length = 4 := by decide

-- Claim boundary: this theorem is about the emitted finite model only.
-- Connecting it back to semantic theory requires the Agda-side faithfulness contract.
"""
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out-dir", default="artifacts/introspective-visual")
    args = parser.parse_args()

    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    png = out / "theory.png"
    receipt_path = out / "vision-receipt.json"
    lean_path = out / "VisionReceipt.lean"

    render(png)
    receipt = detect(png)
    receipt_path.write_text(json.dumps(receipt, indent=2, sort_keys=True) + "\n")
    emit_lean(receipt, lean_path)

    print(
        json.dumps(
            {
                "png": str(png),
                "receipt": str(receipt_path),
                "lean": str(lean_path),
                "ok": receipt["all_expected_edges_detected"],
            }
        )
    )


if __name__ == "__main__":
    main()
