#!/usr/bin/env python3
"""Exact signed node checks against the existing full Newton matrix.

The direct norm logarithmic recurrence is independent of the trace-Newton
matrix reconstruction. The complete J series is generated by the original
owner. No digest, floating arithmetic, or CM recognition pays a gate.
Run under timeout 90s (or longer if explicitly desired).
"""
import ctypes
from pathlib import Path
import subprocess
import tempfile
from time import monotonic
import check_paper9_full_hecke_symmetry as original

P, D = 41, 42
M = P*D


def signed_conv(a, b, n):
    """Exact signed convolution via separate nonnegative streams."""
    ap = [max(x, 0) for x in a]
    am = [max(-x, 0) for x in a]
    bp = [max(x, 0) for x in b]
    bm = [max(-x, 0) for x in b]
    return [x+y-z-w for x,y,z,w in zip(
        original.conv(ap, bp, n), original.conv(am, bm, n),
        original.conv(ap, bm, n), original.conv(am, bp, n))]


def inverse(h, n):
    """Newton doubling in the original truncated q-ring; h[0]=1."""
    assert h[0] == 1
    v = [1]
    while len(v) < n+1:
        m = min(2*len(v), n+1)-1
        err = [-x for x in signed_conv(h[:m+1], v, m)]
        err[0] += 2
        v = signed_conv(v, err, m)
    assert signed_conv(h, v, n) == [1]+[0]*n
    return v


def evaluate_row(row, y):
    z = 0
    for a in reversed(row):
        z = z*y+a
    return z


def check_node(y, j, phi, powers):
    h = j[:M+1]
    h[1] -= y
    dh = [i*a for i,a in enumerate(h)]
    ell = signed_conv(dh, inverse(h, M), M)
    assert ell[0] == 0
    assert signed_conv(h, ell, M) == dh
    v = ell[::P]
    norm = [1]
    for n in range(1, D+1):
        q, rem = divmod(sum(v[k]*norm[n-k] for k in range(1,n+1)), n)
        assert rem == 0
        norm.append(q)
    assert signed_conv(norm, v, D) == [i*a for i,a in enumerate(norm)]
    g = [0]*(D+1)
    for i in range(D//P+1):
        g[i*P] = j[i]
    g[P] -= y
    target = signed_conv(g, norm, D)
    c = [evaluate_row(phi[D-k], y) for k in range(D+1)]
    column = [sum(c[k]*powers[D-k][n-k] for k in range(n+1))
              for n in range(D+1)]
    assert target == column, ("column mismatch", y)
    return len(h)+len(norm)+len(column)


def main():
    start = monotonic()
    root = Path(__file__).resolve().parent
    with tempfile.TemporaryDirectory() as tmp:
        lib = Path(tmp)/"mul.so"
        subprocess.run(["g++","-O3","-shared","-fPIC",
            str(root/"paper9_hecke_packed_mul.cpp"),"-lgmp","-o",str(lib)],check=True)
        dll = ctypes.CDLL(str(lib))
        original._mul = dll.multiply
        original._mul.argtypes = [ctypes.c_char_p,ctypes.c_size_t,
            ctypes.c_char_p,ctypes.c_size_t,ctypes.c_void_p,ctypes.c_size_t]
        original._mul.restype = None
        phi, diag, fixed, divisions = original.matrix()
        j = original.junit(M)
        powers = [[1]+[0]*D]
        for k in range(D):
            powers.append(original.conv(powers[-1], j[:D+1], D))
        assert all(phi[D-k][D] == int(k==D) for k in range(D+1))
        count = 0
        for a in range(1,22):
            for y in (a,-a):
                count += check_node(y,j,phi,powers)
            print("signed pair",a,"cumulative equations",count,
                  "seconds",round(monotonic()-start,3),flush=True)
        assert count == 42*(1723+43+43)
        print("PASS",count,"exact signed-node equations; seconds",
              monotonic()-start,flush=True)


if __name__ == "__main__":
    main()
