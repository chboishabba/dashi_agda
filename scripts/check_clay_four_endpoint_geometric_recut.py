import itertools as it
import sympy as s
from fractions import Fraction as F
counts={}
def ck(group, x):
    if not x: raise RuntimeError(group)
    counts[group]=counts.get(group,0)+1
# RH: finite normalized telescoping and second-order Taylor coefficients.
z,x=s.symbols('z x'); a=s.symbols('a0:13')
for N in range(1,12):
    ck('RH',s.expand(1+sum((z-1)*a[n]+a[n+1]-a[n] for n in range(N)) - (1+(z-1)*sum(a[:N])+a[N]-a[0]))==0)
for v in range(-6,9):
    f=(v-1)*x+(1+x)**(1-v)-1
    ck('RH',s.diff(f,x).subs(x,0)==0)
    ck('RH',s.diff(f,x,2).subs(x,0)==v*(v-1))
# BSD: two-crossing recurrence and positive tail after first crossing.
for l,m,r in it.product(range(1,4),range(5,8),range(10,13)):
    for p in range(1,10):
        mass=[10-p,-10,p]; xs=[l,m,r]; c1=F(l+m,2); c2=F(m+r,2)
        M=[sum(w*t**j for w,t in zip(mass,xs)) for j in range(14)]
        ck('BSD',M[0]==0)
        for j in range(12): ck('BSD',M[j+2]-(c1+c2)*M[j+1]+c1*c2*M[j]>0)
        signs=[s.sign(t) for t in M[1:]]
        ck('BSD',all(not (signs[i]>0 and signs[i+1]<=0) for i in range(len(signs)-1)))
# NS: orthogonal projection onto k⊙k-perp of symmetric trace-free tensors.
for k in [s.Matrix(t) for t in it.product(range(-1,2),repeat=3) if any(t)]:
    d=k.dot(k); P=s.eye(3)-k*k.T/d
    for u in range(3):
        A=s.zeros(3); A[u,u]=2; A[(u+1)%3,(u+1)%3]=-2; A[u,(u+2)%3]=A[(u+2)%3,u]=1
        b=P*A*k/d; B=k*b.T+b*k.T
        ck('NS',B==B.T and s.trace(B)==0)
        ck('NS',P*(A-B)*k==s.zeros(3,1))
        ck('NS',s.trace(B.T*B)==2*(P*A*k).dot(P*A*k)/d)
        for e in s.eye(3).columnspace():
            v=P*e; Q=k*v.T+v*k.T
            ck('NS',s.trace((A-B).T*Q)==0)
# Hodge: S6 and A6 permutation module standard part generated by any difference.
perms=list(it.permutations(range(6)))
def parity(p): return (-1)**sum(p[i]>p[j] for i in range(6) for j in range(i+1,6))
even=[p for p in perms if parity(p)==1]
ck('Hodge',len(even)==360)
for i,j in it.permutations(range(6),2):
    orbit={(p[i],p[j]) for p in even}
    ck('Hodge',len(orbit)==30)
    mat=s.Matrix.hstack(*[s.eye(6)[:,a]-s.eye(6)[:,b] for a,b in sorted(orbit)])
    ck('Hodge',mat.rank()==5)
print(counts, 'TOTAL',sum(counts.values()))
